func TestQueryCacheFIFOAndKey(t *testing.T) {
	base := mustRender(t, EngineJoern, testJavaTaintIntent())
	key := QueryCacheKey(base)
	if key == "" {
		t.Fatal("empty cache key")
	}
	same := base
	same.Params = map[string]any{"b": 2, "a": 1}
	other := base
	other.Params = map[string]any{"a": 1, "b": 2}
	if QueryCacheKey(same) != QueryCacheKey(other) {
		t.Error("cache key is not stable across map insertion order")
	}
	changed := base
	changed.Template = "joern/java/taint-reachable-v3"
	if QueryCacheKey(base) == QueryCacheKey(changed) {
		t.Error("cache key ignores template version")
	}

	cache := NewQueryCache(2)
	keyA := "a"
	keyB := "b"
	keyC := "c"
	specA := base
	specA.ID = "a"
	specB := base
	specB.ID = "b"
	specC := base
	specC.ID = "c"
	cache.Put(keyA, specA)
	cache.Put(keyB, specB)
	cache.Put(keyB, specB)
	if cache.Len() != 2 {
		t.Fatalf("cache length after update = %d, want 2", cache.Len())
	}
	cache.Put(keyC, specC)
	if cache.Len() != 2 {
		t.Fatalf("cache length = %d, want 2", cache.Len())
	}
	if _, ok := cache.Get(keyA); ok {
		t.Error("oldest cache entry was not evicted")
	}
	if _, ok := cache.Get(keyB); !ok {
		t.Error("cache entry B missing")
	}
	if _, ok := cache.Get(keyC); !ok {
		t.Error("cache entry C missing")
	}
	if cache.Hits() != 2 {
		t.Errorf("cache hits = %d, want 2", cache.Hits())
	}
	if cache.Misses() != 1 {
		t.Errorf("cache misses = %d, want 1", cache.Misses())
	}

	if _, ok := cache.Get(keyC); !ok {
		t.Fatal("cache entry C missing on second read")
	}
	returned, _ := cache.Get(keyC)
	returned.Params["mutated"] = true
	fresh, _ := cache.Get(keyC)
	if _, mutated := fresh.Params["mutated"]; mutated {
		t.Error("cache returned a map aliased with the stored spec")
	}
}

func TestSafeEngineIDAndJoin(t *testing.T) {
	cases := map[string]string{
		"":             "query",
		"../../escape": "escape",
		"qs-abc":       "qs-abc",
		"a/b\\c":       "a_b_c",
		"CON":          "_CON",
		"CON.txt":      "_CON.txt",
	}
	for input, want := range cases {
		if got := safeEngineID(input); got != want {
			t.Errorf("safeEngineID(%q) = %q, want %q", input, got, want)
		}
	}
	base := t.TempDir()
	if _, err := safeJoin(base, "..", "escape"); err == nil {
		t.Error("safeJoin allowed a traversal")
	}
	joined, err := safeJoin(base, "nested", "query.ql")
	if err != nil {
		t.Fatalf("safeJoin: %v", err)
	}
	if !strings.HasPrefix(joined, base) {
		t.Errorf("safeJoin = %q, base %q", joined, base)
	}
}

