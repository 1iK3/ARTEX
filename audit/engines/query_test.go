func TestRenderAllAndUnsupported(t *testing.T) {
	specs, err := RenderAll(testJavaTaintIntent())
	if err != nil {
		t.Fatalf("RenderAll: %v", err)
	}
	if len(specs) != 3 {
		t.Fatalf("RenderAll specs = %d, want 3", len(specs))
	}
	if specs[0].Engine != EngineCodeQL || specs[1].Engine != EngineJoern || specs[2].Engine != EngineCodeGraph {
		t.Errorf("RenderAll order = %v", []string{specs[0].Engine, specs[1].Engine, specs[2].Engine})
	}

	goSink := sinkIntent(audit.Go, "CWE-89", "Query")
	goSpecs, err := RenderAll(goSink)
	if err != nil {
		t.Fatalf("RenderAll Go sink: %v", err)
	}
	if len(goSpecs) != 2 {
		t.Fatalf("Go RenderAll specs = %d, want joern+codegraph", len(goSpecs))
	}
	if _, err := Render(EngineCodeQL, goSink); !errors.Is(err, ErrUnsupported) {
		t.Fatalf("CodeQL Go render error = %v, want ErrUnsupported", err)
	}
	if _, err := Render("unknown", goSink); !errors.Is(err, ErrUnsupported) {
		t.Fatalf("unknown engine error = %v, want ErrUnsupported", err)
	}

	pythonTaint := taintIntent(audit.Python, "CWE-89", "execute", "request")
	if _, err := Render(EngineCodeQL, pythonTaint); !errors.Is(err, ErrUnsupported) {
		t.Fatalf("CodeQL Python taint error = %v, want ErrUnsupported", err)
	}

	pythonSink := sinkIntent(audit.Python, "CWE-89", "execute")
	if _, err := Render(EngineCodeQL, pythonSink); !errors.Is(err, ErrUnsupported) {
		t.Fatalf("CodeQL Python sink error = %v, want ErrUnsupported (pack/template not verified)", err)
	}

	jsSink := sinkIntent(audit.TypeScript, "CWE-79", "innerHTML")
	if _, err := Render(EngineCodeQL, jsSink); !errors.Is(err, ErrUnsupported) {
		t.Fatalf("CodeQL TypeScript sink error = %v, want ErrUnsupported", err)
	}

	rustSink := sinkIntent(audit.Rust, "CWE-78", "Command")
	if _, err := Render(EngineJoern, rustSink); !errors.Is(err, ErrUnsupported) {
		t.Fatalf("Joern Rust error = %v, want ErrUnsupported", err)
	}
}

func TestRenderValidatesSinksAndTaintSources(t *testing.T) {
	sinkOnly := DetectionIntent{
		ID: "bad-sink", Language: audit.Java, CWE: "CWE-89", QueryKind: QueryKindSink,
		Title: "bad sink",
	}
	if _, err := Render(EngineCodeGraph, sinkOnly); !errors.Is(err, ErrInvalidQuery) {
		t.Fatalf("empty sink error = %v", err)
	}
	taintNoSource := DetectionIntent{
		ID: "bad-taint", Language: audit.Java, CWE: "CWE-89", QueryKind: QueryKindTaint,
		Title: "bad taint", Sinks: []Pattern{{Pattern: "executeQuery", Match: MatchMethodCall}},
	}
	if _, err := Render(EngineCodeGraph, taintNoSource); !errors.Is(err, ErrInvalidQuery) {
		t.Fatalf("empty source error = %v", err)
	}
	phase := DetectionIntent{
		ID: "phase", Language: audit.Java, CWE: "", QueryKind: QueryKindControlFlow,
		Title: "phase requirement",
	}
	q, err := Render(EngineCodeGraph, phase)
	if err != nil {
		t.Fatalf("CodeGraph phase intent: %v", err)
	}
	if !strings.Contains(q.QueryText, "Trace source to sink") {
		t.Errorf("phase CodeGraph query = %q", q.QueryText)
	}
	badKind := phase
	badKind.QueryKind = "not-a-kind"
	if _, err := Render(EngineCodeGraph, badKind); !errors.Is(err, ErrInvalidQuery) {
		t.Fatalf("bad query kind error = %v", err)
	}
}

