func TestRenderFallsBackFromTaintToSink(t *testing.T) {
	const language = "fallback-lang"
	spec := templateSpec{
		ID: "codeql/fallback/sink-v1", Engine: EngineCodeQL, Language: language,
		Kind: QueryKindSink, Format: FormatSARIF, render: renderCodeQLJavaSink,
	}
	key := templateKey(EngineCodeQL, language, QueryKindSink)
	templatesByKey[key] = spec
	templatesByID[EngineCodeQL+"\x00"+spec.ID] = spec
	defer func() {
		delete(templatesByKey, key)
		delete(templatesByID, EngineCodeQL+"\x00"+spec.ID)
	}()

	intent := DetectionIntent{
		ID: "fallback", Language: language, CWE: "CWE-89", Title: "fallback taint",
		QueryKind: QueryKindTaint,
		Sources:   []Pattern{{Pattern: "getParameter", Match: MatchMethodCall}},
		Sinks:     []Pattern{{Pattern: "executeQuery", Match: MatchMethodCall}},
	}
	query, err := Render(EngineCodeQL, intent)
	if err != nil {
		t.Fatalf("fallback Render: %v", err)
	}
	if query.QueryKind != QueryKindSink || query.Template != spec.ID {
		t.Fatalf("fallback spec = %+v", query)
	}
	if query.Provenance["fallback"] != true || query.Provenance["fallback_from"] != QueryKindTaint {
		t.Errorf("fallback provenance = %+v", query.Provenance)
	}
}

