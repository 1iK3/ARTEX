func TestRenderCodeQLJavaTaint(t *testing.T) {
	q := mustRender(t, EngineCodeQL, testJavaTaintIntent())
	if q.Engine != EngineCodeQL || q.Language != audit.Java || q.QueryKind != QueryKindTaint {
		t.Fatalf("unexpected spec identity: %+v", q)
	}
	if q.Template != TemplateCodeQLJavaTaint {
		t.Errorf("template = %q, want %q", q.Template, TemplateCodeQLJavaTaint)
	}
	if q.ExpectedFormat != FormatSARIF {
		t.Errorf("expected format = %q, want sarif", q.ExpectedFormat)
	}
	if q.GeneratedBy != "template" {
		t.Errorf("generated by = %q", q.GeneratedBy)
	}
	if version := q.Provenance["template_version"]; version != TemplateVersion {
		t.Errorf("provenance template_version = %v, want %v", version, TemplateVersion)
	}
	if !strings.HasPrefix(q.ID, "qs-") {
		t.Errorf("query ID = %q, want qs- prefix", q.ID)
	}
	if !strings.HasPrefix(q.QueryPath, "queries/codeql/") || !strings.HasSuffix(q.QueryPath, "query.ql") {
		t.Errorf("query path = %q", q.QueryPath)
	}
	for _, want := range []string{
		"DataFlow::ConfigSig",
		"TaintTracking::Global<ArtexConfig>",
		"PathGraph",
		"flowPath",
		"MethodCall",
		"getAnArgument",
		"isBarrier",
		"@kind path-problem",
		`"executeQuery"`,
		`"getParameter"`,
		`"setString"`,
		"@id artex/generated/taint/qs-",
	} {
		if !strings.Contains(q.QueryText, want) {
			t.Errorf("CodeQL query missing %q:\n%s", want, q.QueryText)
		}
	}
	if !containsString(paramStringSlice(q.Params, "sinks"), "executeQuery") {
		t.Errorf("params sinks = %v", paramStringSlice(q.Params, "sinks"))
	}

	again := mustRender(t, EngineCodeQL, testJavaTaintIntent())
	if again.ID != q.ID || again.QueryText != q.QueryText {
		t.Errorf("rendering is not stable: IDs %q/%q", again.ID, q.ID)
	}
}

