func sinkIntent(language, cwe string, sinks ...string) DetectionIntent {
	patterns := make([]Pattern, 0, len(sinks))
	for _, sink := range sinks {
		patterns = append(patterns, Pattern{Pattern: sink, Match: MatchMethodCall})
	}
	return DetectionIntent{
		ID:               "intent-" + language + "-" + cwe,
		Origin:           OriginSinkRule,
		Language:         language,
		CWE:              cwe,
		Title:            language + " " + cwe + " sink",
		QueryKind:        QueryKindSink,
		Sinks:            patterns,
		PreferredEngines: []string{EngineCodeQL, EngineJoern, EngineCodeGraph},
	}
}

func taintIntent(language, cwe, sink, source string) DetectionIntent {
	intent := sinkIntent(language, cwe, sink)
	intent.QueryKind = QueryKindTaint
	intent.Sources = []Pattern{{Pattern: source, Match: MatchMethodCall}}
	return intent
}

func containsString(values []string, want string) bool {
	for _, value := range values {
		if value == want {
			return true
		}
	}
	return false
}
